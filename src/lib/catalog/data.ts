type TileInput = Omit<Product, "unit" | "brand" | "images" | "stock" | "inShowroom" | "tags" | "specs" | "usage" | "features"> &
  Partial<Pick<Product, "stock" | "inShowroom" | "tags" | "specs" | "usage" | "features">>;

/** Karo ürünleri için ortak alanları dolduran yardımcı */
function tile(p: TileInput): Product {
  const specs: Record<string, string> = {
    Ebat: p.size ? `${p.size} cm` : "—",
    ...(p.thickness && { Kalınlık: p.thickness }),
    ...(p.surface && { Yüzey: p.surface[0].toUpperCase() + p.surface.slice(1) }),
    ...(p.packPieces && p.packSize && { Kutu: `${p.packPieces} adet / ${p.packSize.toLocaleString("tr-TR")} m²` }),
    ...(p.palletM2 && { Palet: `${p.palletM2.toLocaleString("tr-TR")} m²` }),
    ...p.specs,
  };
  return {
    brand: "Seravit Seçkisi",
    images: [],
    unit: "m2",
    wholesaleTiers: tileTiers,
    stock: "stokta",
    inShowroom: true,
    tags: [],
    usage: ["ic-mekan"],
    features: ["porselen", "rektifiye", "yer", "duvar"],
    ...p,
    specs,
  };
}

